/**
 * اكتشاف دستور اللعبة من حالة الغرفة أو من حزمة الجلسة.
 * يجب أن يبقى متوافقاً مع GameEngineRegistry.detectGameType في السيرفر.
 */
export function detectRulebookId(state: any): RulebookId {
  if (!state) return "GENERIC";
  if (state.unoState) return "UNO";

  if (state.connectFourState) return "CONNECT_FOUR";
  if (state.checkersState) return "CHECKERS";
  if (state.bingoState) return "BINGO";

  const key = state.gameKey || state.key || state.presetKey || "";
  const themeId = state.themeId || "";
  const title = state.themeTitle || "";
  const mechanism = state.rulesConfig?.turnMechanism;
  const ownership = state.rulesConfig?.ownershipSystem;
  const archetype = state.archetype;
  const tilesCount = state.tiles?.length || state.boardSize || 0;

  if (key === "CONNECT_FOUR" || mechanism === "GRID_PLACEMENT") {
    return "CONNECT_FOUR";
  }
  if (key === "CHECKERS_CLASSIC" || mechanism === "CHECKERS_MOVE") {
    return "CHECKERS";
  }
  if (key === "BINGO_NIGHT" || mechanism === "BINGO_CALL") {
    return "BINGO";
  }
  if (key === "SOCIAL_MAFIA_SPY" || themeId.includes("MAFIA") || archetype === "SOCIAL_DEDUCTION" || mechanism === "SOCIAL_DISCUSSION_VOTE") {
    return "MAFIA";
  }
  if (key === "WORLD_CONQUEST_RISK" || ownership === "CONQUER_REGIONS" || mechanism === "TERRITORY_COMMAND") {
    return "RISK";
  }
  if (key === "LUDO_CLASSIC" || state.isLudo || state.ludoState || themeId.includes("LUDO") || title.includes("لودو") || title.includes("جاكارو") || title.includes("Ludo")) {
    return "LUDO";
  }
  if (key === "TACTICAL_CARDS_UNO" || key === "UNO" || themeId === "TACTICAL_CARDS_UNO" || title.includes("أونو") || title.includes("Uno") || title.includes("UNO")) {
    return "UNO";
  }
  if (key === "SNAKES_AND_LADDERS_RPG" || tilesCount === 100 || title.includes("سلم") || title.includes("ثعبان") || title.includes("Snakes") || state.tiles?.some((t: any) => t.jumpToIndex !== undefined)) {
    return "SNAKES_AND_LADDERS";
  }
  if (key === "MONOPOLY_CLASSIC" || key === "RIYADH_VIP" || themeId === "MONOPOLY_CLASSIC" || themeId === "RIYADH_VIP" || ownership === "BUY_AND_RENT" || title.includes("مونوبولي") || title.includes("Monopoly") || title.includes("عقارات")) {
    return "MONOPOLY";
  }
  return "GENERIC";
}
